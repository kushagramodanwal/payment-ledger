-- Fresh PostgreSQL schema for wallet-System-main.
-- Run with: psql "$DATABASE_URL" -f src/config/schema.sql

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL CHECK (length(trim(name)) >= 2),
  email TEXT NOT NULL CONSTRAINT users_email_key UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT users_email_lowercase CHECK (email = lower(email))
);

CREATE TABLE IF NOT EXISTS wallets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL CONSTRAINT wallets_user_id_key UNIQUE
    REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL DEFAULT 'My Wallet',
  balance_paise BIGINT NOT NULL DEFAULT 0 CHECK (balance_paise >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idempotency_key UUID NOT NULL CONSTRAINT transactions_idempotency_key_key UNIQUE,
  sender_wallet_id INTEGER NOT NULL REFERENCES wallets(id),
  receiver_wallet_id INTEGER NOT NULL REFERENCES wallets(id),
  amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
  status TEXT NOT NULL CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT transactions_different_wallets CHECK (sender_wallet_id <> receiver_wallet_id)
);

CREATE INDEX IF NOT EXISTS idx_transactions_sender_id ON transactions(sender_wallet_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_transactions_receiver_id ON transactions(receiver_wallet_id, id DESC);
